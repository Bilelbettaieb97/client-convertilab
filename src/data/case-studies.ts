function buildFullStudy(cs: CaseStudy, extra: Omit<FullCaseStudy, "sector" | "client" | "title" | "technologies">): FullCaseStudy {
  return {
    sector: cs.sector,
    client: cs.client,
    title: cs.title,
    technologies: cs.technologies,
    ...extra,
  };
}

